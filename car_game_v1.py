def park():
   d.goto(-315,130)
   d3.goto(-340,130)
   d1.goto(-300,90)
   d2.goto(-350,90)
def forward(Sk=0):
    for i in range(10):
        d.setheading(0)
        d3.setheading(0)
        d1.setheading(0)
        d2.setheading(0)
        d.forward(3)
        d3.forward(3)
        d1.forward(3)
        d2.forward(3)
  
def backward():
    for i in range(10):
        d.setheading(180)
        d3.setheading(180)
        d1.setheading(180)
        d2.setheading(180)
        d.forward(3)
        d3.forward(3)
        d1.forward(3)
        d2.forward(3)
def up():
    for i in range(10):
        d.setheading(90)
        d3.setheading(90)
        d1.setheading(90)
        d2.setheading(90)
        d.forward(3)
        d3.forward(3)
        d1.forward(3)
        d2.forward(3)
def down():
    for i in range(10):
        d.setheading(-90)
        d3.setheading(-90)
        d1.setheading(-90)
        d2.setheading(-90)
        d.forward(3)
        d3.forward(3)
        d1.forward(3)
        d2.forward(3)
    
s.onkey(forward,"Right")
s.onkey(backward,"Left")
s.onkey(up,"Up")
s.onkey(down,"Down")
s.onkey(park,"p")

s.listen()
gameon = True
while gameon:
   s.update()
